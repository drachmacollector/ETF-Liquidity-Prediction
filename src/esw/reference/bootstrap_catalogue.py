"""One-off builder for the P03 catalogue tables (first pass, agent-labelled).

`reference/incidents.csv` and `reference/operational_events.csv` are written from the facts below,
each with sources found in P03 (EDGAR filings read directly; press and issuer pages via web search).
After writing, the CSVs are the source of truth: labels change only through a logged decision
(P03 T03.6, MI-08). Grades: [V] primary document read; [R] reputable secondary report(s); [K] widely
known, not yet checked against a document. Times are UTC (`Z`). Conservative `known_at` rules follow
the P03 dating protocol (publication date at 18:00 local when only a date is known).
"""

from __future__ import annotations

import pandas as pd

from esw.config import Settings, get_settings

EDGAR = "https://www.sec.gov/Archives/edgar/data"


def _ids(settings: Settings, groups: list[str], issuer: str | None = None) -> str:
    ind = pd.read_csv(settings.path("reference") / "instruments_in.csv", dtype=str, keep_default_na=False)
    m = ind["group"].isin(groups) & (ind["include"] == "true")
    if issuer:
        m &= ind["issuer"].str.contains(issuer, case=False)
    return ";".join(ind.loc[m, "instrument_id"])


