def capacity(settings: Settings) -> pd.DataFrame:
    """10-Q/10-K regex extraction (USCF LP funds) + 8-K rows + descriptive rows."""
    x = pd.read_csv(settings.path("raw") / "sec_edgar" / "capacity_extract_P03.csv")
    x["known_at"] = pd.to_datetime(x["known_at"], utc=True).dt.strftime("%Y-%m-%dT%H:%M:%SZ")
    x = x.drop_duplicates(subset=["instrument_id", "as_of", "metric", "value"])
    # cumulative registered shares never fall: drop obvious parse errors (e.g. "2,280,000" for 2.28bn)
    keep = []
    for _, g in x[x["metric"] == "registered_shares_total"].sort_values("as_of").groupby("instrument_id"):
        run_max = g["value"].cummax().shift().fillna(0)
        keep.append(g[g["value"] >= 0.5 * run_max])
    x = pd.concat([*keep, x[x["metric"] != "registered_shares_total"]], ignore_index=True)
    x["unit"] = "shares"
    x["notes"] = x["form"] + " (as reported in that filing; later filings may restate for splits)"
    rows = [
        dict(zip(["instrument_id", "as_of", "metric", "value", "known_at", "source_url"], r, strict=True))
        | {"unit": "shares", "notes": "8-K"}
        for r in CAPACITY_8K
    ]
    rows += [
        dict(zip(["instrument_id", "as_of", "metric", "value", "known_at", "source_url"], r, strict=True))
        | {"unit": "text", "notes": "registration type"}
        for r in CAPACITY_TYPE
    ]
    out = pd.concat(
        [
            x[["instrument_id", "as_of", "metric", "value", "unit", "known_at", "source_url", "notes"]],
            pd.DataFrame(rows),
        ],
        ignore_index=True,
    )
    return out.sort_values(["instrument_id", "as_of", "metric"]).reset_index(drop=True)


def write_capacity(settings: Settings | None = None) -> None:
    settings = settings or get_settings()
    capacity(settings).to_csv(settings.path("reference") / "capacity_us.csv", index=False)
